-- ------------------------------------------------------------
-- 3) SERVER 1 PUBLIC CHAT
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.online_chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
