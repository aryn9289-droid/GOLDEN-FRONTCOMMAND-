-- ------------------------------------------------------------
-- 5) TWO-SIDED DIPLOMACY REQUESTS
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.diplomacy_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id INTEGER NOT NULL DEFAULT 1,
    requester_user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    recipient_user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    requester_country_iso TEXT NOT NULL,
    target_country_iso TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('ally','war','peace')),
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','accepted','rejected','cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    responded_at TIMESTAMPTZ
);

ALTER TABLE public.diplomacy_requests ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "diplomacy_select_participants" ON public.diplomacy_requests;
DROP POLICY IF EXISTS "diplomacy_insert_requester" ON public.diplomacy_requests;
DROP POLICY IF EXISTS "diplomacy_update_recipient" ON public.diplomacy_requests;
DROP POLICY IF EXISTS "diplomacy_delete_requester" ON public.diplomacy_requests;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.diplomacy_requests TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.diplomacy_requests_id_seq TO authenticated;

CREATE POLICY "diplomacy_select_participants"
ON public.diplomacy_requests FOR SELECT TO authenticated
USING (
    auth.uid() = requester_user_id
    OR auth.uid() = recipient_user_id
);

CREATE POLICY "diplomacy_insert_requester"
ON public.diplomacy_requests FOR INSERT TO authenticated
WITH CHECK (
    auth.uid() = requester_user_id
    AND requester_user_id <> recipient_user_id
);

CREATE POLICY "diplomacy_update_recipient"
ON public.diplomacy_requests FOR UPDATE TO authenticated
USING (auth.uid() = recipient_user_id)
WITH CHECK (auth.uid() = recipient_user_id);

CREATE POLICY "diplomacy_delete_requester"
ON public.diplomacy_requests FOR DELETE TO authenticated
USING (auth.uid() = requester_user_id);

CREATE INDEX IF NOT EXISTS diplomacy_recipient_status_idx
ON public.diplomacy_requests(recipient_user_id, status, created_at DESC);

CREATE INDEX IF NOT EXISTS diplomacy_requester_status_idx
ON public.diplomacy_requests(requester_user_id, status, created_at DESC);


-- ------------------------------------------------------------
-- 6) REALTIME FOR CHAT
-- Safe check: add the table only if it is not already published.
-- ------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime'
    ) AND NOT EXISTS (
        SELECT 1
        FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'public'
          AND tablename = 'online_chat_messages'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.online_chat_messages;
    END IF;
END $$;


